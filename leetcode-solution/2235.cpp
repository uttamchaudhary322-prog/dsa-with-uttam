// Problem: 2235. Add Two Integers
// Difficulty: Easy
// Link: https://leetcode.com/problems/add-two-integers/
//
// Approach: Return the sum of the two given integers.
//
// Time Complexity: O(1)
// Space Complexity: O(1)

class Solution {
public:
    int sum(int num1, int num2) {
        return num1 + num2;
    }
};